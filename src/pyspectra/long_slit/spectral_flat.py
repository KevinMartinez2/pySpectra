def flat_test(flat_files, files, method = 'median', 
         fit_func = 'spline3', order = 50,
         view_stats = True, correct = True,
         output_dir = None, overwrite = False):

    """
    This function is used to know the response of 
    the detector due to the sensibility of different
    wavelenghts and the illumination of the field, by
    creating a flat_master file.
    Optionally, can plot the statistics of the flat_master
    and also correct by this image a set of files.

    Parameters
    ----------
    flat_files : list
        List of paths to the flat files to be combined
        for create the flat_master file.
        All images must have identical dimensions.
        
    files : list of str
        List of paths to the FITS files to be corrected
        by the flat_master.

    method : {'median', 'mean', 'min', 'max'}, optional
        Statistical estimator used to combine the flat images:

        - 'median' : Pixel-wise median (robust against outliers)
        - 'mean'   : Pixel-wise arithmetic mean
        - 'min'    : Pixel-wise minimum
        - 'max'    : Pixel-wise maximum

        Default is 'median'.

    fit_func : {'spline1', 'spline3', 'legendre', 'chebyshev'}, optional
        Function to be used for fit the response of the detector along 
        the dispersion axis.

        Default is 'spline3'.

    order : int, optional
        Order of the fitting function or the number of inside knots for splines.

        Default is 50.

    view_stats : Boolean, optional
        If True, plot basic statistics (mean, median, std, etc.)
        of the flat_master.
        Default is True.

    correct : Boolean, optional
        If True, correct by the flat_master each file in files.
        Default is True.

    output_dir : str, optional
        Output directory where the flat corrected files must be saved.
        If None, a directory called stage1 is created and the files are 
        saved there.

    overwrite : Boolean, optional
        If True, existing output files are overwritten.

        If False, original files are never overwritten. The flat-corrected
        images are written to output_dir using the suffix "_f.fits".
        If a file with that name already exists, this is overwritten.
    
        Default is False.

    Returns
    -------
    None
        This function creates a master flat image from flat_files.
        Depending on the input parameters, it may:
    
        - Correct by the master flat a set of images in files
          (correct=True).
        - Overwrite existing files if overwrite=True.
    
        No objects are returned; all operations are performed on disk.

    Notes
    -----
    - Flat files must have the same size.
    - Each file in files must have the same size as the flat_master


    Raises
    ------
    ValueError
        If flat images do not share identical dimensions.
        If any image in 'files' does not match the flat_master dimensions.
        If 'method' is not one of {'median', 'mean', 'min', 'max'}.
        If 'fit_func' is not one of {'spline1', 'spline3', 'legendre', 'chebyshev'}
    """

    # Check the path of output_dir
    output_dir = Path(output_dir) if output_dir is not None else Path(flat_files[0]).parent / "stage1"
    output_dir.mkdir(parents=True, exist_ok=True)

    ######################################
    # Create and open the flat_main
    ######################################
    
    flat_path = output_dir / "flat_main.fits"
    combine(flat_files, align = False, sigma = 3, method = method, result_img = str(flat_path))

    with fits.open(flat_path) as hdul:
        flat = hdul[0].data
        flat_hdr = hdul[0].header

    ######################################
    # Determine the dispersion and spatial axis
    ######################################

    # Determine dispersion axis
    disp_axis = flat_hdr.get('DISPAXIS', None)

    if disp_axis not in (1, 2):
        raise ValueError("DISPAXIS not defined or invalid in header")

    # Determine spatial axis
    spatial_axis = 0 if disp_axis == 1 else 1

    ######################################
    # Fit the response in the dispersion-axis
    ######################################

    

    

    ######################################
    # Fit the response in the spatial-axis
    ######################################
    
    
    # Get the response
    center = flat.shape[spatial_axis] // 2
    
    lo = max(center - 10, 0)
    hi = min(center + 10 + 1, flat.shape[spatial_axis]) # The plus 1 is for not exclude hi index in the lists below
    
    if spatial_axis == 0:
        region = flat[lo:hi, :]
        response = np.nanmedian(region, axis=0)
    else:
        region = flat[:, lo:hi]
        response = np.nanmedian(region, axis=1)

    # Fit response 
    pixs = np.arange(len(response))

    if fit_func == "legendre":
        coeff = np.polynomial.legendre.legfit(pixs, response, order)
        fit = np.polynomial.legendre.legval(pixs, coeff)

    elif fit_func == "chebyshev":
        coeff = np.polynomial.chebyshev.chebfit(pixs, response, order)
        fit = np.polynomial.chebyshev.chebval(pixs, coeff)

    elif fit_func == "spline1":
        n_knots = order
        knots = np.linspace(pixs[0], pixs[-1], n_knots+2)[1:-1] # The plus 2 is for taking into account the extremes of the arange
        spline = LSQUnivariateSpline(pixs, response, knots, k=1)
        fit = spline(pixs)

    elif fit_func == "spline3":
        n_knots = order
        knots = np.linspace(pixs[0], pixs[-1], n_knots+2)[1:-1] # The plus 2 is for taking into account the extremes of the arange
        spline = LSQUnivariateSpline(pixs, response, knots, k=3)
        fit = spline(pixs)

    else:
        raise ValueError("Invalid fitting function")

    # Compute the rms
    residuals = response - fit
    rms = np.sqrt(np.nanmean(residuals**2))

    print(f"Fit made with {fit_func} function")
    print(f"Max response value: {np.nanmax(response)}")
    print(f"Min response value: {np.nanmin(response)}")
    print(f"RMS: {rms:.6f}")
    

    # Create a normalized flat
    flat_norm = np.ones_like(flat)
    
    if spatial_axis == 0:
        flat_norm[lo:hi, :] = flat[lo:hi, :] / fit
    else:
        flat_norm[:, lo:hi] = flat[:, lo:hi] / fit[:, None]
        
    flat_norm_hdr = flat_hdr.copy()
    
    flat_norm_hdr['FITFUNC'] = (fit_func, 'Function used to fit the response')
    if fit_func in ('spline1', 'spline3'):
        flat_norm_hdr['KNOTS'] = (order, 'Internal knots')
    else:
        flat_norm_hdr['ORDER'] = (order, 'Fit order')
    flat_norm_hdr['RMS'] = (round(rms,6), 'RMS value of the fit')

    flat_norm_path = output_dir / "flat_master.fits"

    fits.PrimaryHDU(data=flat_norm, header=flat_norm_hdr).writeto(
        str(flat_norm_path), overwrite=True
    )
    
    ######################################
    # Plot the statistics of flat_master.fits
    ######################################
    if view_stats:
        with fits.open(str(flat_norm_path)) as hdul:
            flat_master_data = hdul[0].data
    
        print("Master Flat Statistics")
        print("----------------------")
        print(f"Npix        : {flat_master_data.size}")
        print(f"Mean        : {np.nanmean(flat_master_data):.2f}")
        print(f"Median      : {np.nanmedian(flat_master_data):.2f}")
        print(f"RMS         : {rms:.5f}")
        print(f"Std         : {np.nanstd(flat_master_data):.5f}")
        print(f"Min         : {np.nanmin(flat_master_data):.5f}")
        print(f"Max         : {np.nanmax(flat_master_data):.5f}")

    ######################################
    # Correct each file using the flat_master
    ######################################
    if correct:
        print('Response correction applied to:')
    
        for f in files:
            with fits.open(f) as hdul:
                data = hdul[0].data.astype(float)
                hdr = hdul[0].header

            if data.shape != flat_norm.shape:
                raise ValueError(
                    f"Image {f} has shape {data.shape}, "
                    f"but master flat has shape {flat_norm.shape}.")

            data = data / flat_norm

            hdr.add_history('--- Response correction ---')
            hdr.add_history('Response correction have been made using')
            hdr.add_history(str(flat_norm_path))
            hdr.add_history(f'Fit function: {fit_func}')
            if fit_func in ('spline1', 'spline3'):
                hdr.add_history(f'Internal knots: {order}')
            else:
                hdr.add_history(f'Fit order: {order}')
            hdr.add_history(f'RMS: {rms:.6f}')

            if overwrite == True:
                out_file = f
            else:
                p = Path(f)
                out_file = output_dir / (p.stem + "_f" + p.suffix)

            fits.writeto(out_file, data, hdr, overwrite=overwrite)
            print(f"File : {out_file}")