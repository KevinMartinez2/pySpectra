def flat(flat_files, files, method='median',
         width=50, plot_response=False,
         fit_func='spline3', order=50,
         plot_fit=False,
         view_stats=True, correct=True,
         output_dir=None, overwrite=False):

    """
    This function creates a normalized master flat (response image) from
    a set of flat-field exposures.
    
    The response spectrum is estimated from the brightest region of the
    slit and used to remove the wavelength-dependent sensitivity pattern
    from the combined flat image.
    
    Optionally, the resulting master flat can be applied to a set of
    science images.

    Parameters
    ----------
    flat_files : list
        List of paths to the flat files to be combined
        for create the flat_master file.
        All images must have identical dimensions.
        
    files : list of str
        List of paths to the FITS files to be corrected
        by the flat_master.

    method : {'median', 'mean', 'min', 'max'}, optional
        Statistical estimator used to combine the flat images:

        - 'median' : Pixel-wise median (robust against outliers)
        - 'mean'   : Pixel-wise arithmetic mean
        - 'min'    : Pixel-wise minimum
        - 'max'    : Pixel-wise maximum

        Default is 'median'.

    width : int, optional
        Width (in pixels) of the spatial region centered on the brightest
        part of the slit used to estimate the response spectrum.
        Default is 50.

    plot_response : bool, optional
        If True, display the extracted one-dimensional response spectrum
        used to construct the master flat.
        Default is False.    

    view_stats : Boolean, optional
        If True, plot basic statistics (mean, median, std, etc.)
        of the flat_master.
        Default is True.

    correct : Boolean, optional
        If True, correct by the flat_master each file in files.
        Default is True.

    output_dir : str, optional
        Output directory where the flat corrected files must be saved.
        If None, a directory called stage2 is created and the files are 
        saved there.

    overwrite : Boolean, optional
        If True, existing output files are overwritten.

        If False, original files are never overwritten. The flat-corrected
        images are written to output_dir using the suffix "_f.fits".
        If a file with that name already exists, this is overwritten.
    
        Default is False.

    Returns
    -------
    None
        Creates a normalized master flat (response image) from the
        input flat-field exposures.
    
        Optionally applies the response correction to the images
        provided in 'files'.
    
        All outputs are written to disk.

    Notes
    -----
    - Flat files must have the same size.
    - Each file in files must have the same size as the generated
      master flat.
    - The detector dispersion axis is determined from the FITS keyword
      DISPAXIS.
    - A spatial profile is estimated near the center of the dispersion
      axis to identify the brightest region of the slit.
    - The response spectrum is extracted from this region using the
      median signal across a user-defined spatial width.
    - The master flat is generated by dividing the combined flat image
      by the extracted response spectrum.


    Raises
    ------
    ValueError
        If flat images do not share identical dimensions.
    
        If any image in 'files' does not match the dimensions of the
        master flat.
    
        If 'DISPAXIS' is missing from the FITS header or is not equal
        to 1 or 2.
    
        If 'method' is not one of
        {'median', 'mean', 'min', 'max'}.
    """

    # Check the path of output_dir
    output_dir = Path(output_dir) if output_dir is not None else Path(flat_files[0]).parent / "stage2"
    output_dir.mkdir(parents=True, exist_ok=True)

    ######################################
    # Create and open the flat_combined
    ######################################

    flat_path = output_dir / "flat_combined.fits"
    combine(flat_files, align = False, sigma = 3, method = method, result_img = str(flat_path))

    with fits.open(flat_path) as hdul:
        flat = hdul[0].data
        flat_hdr = hdul[0].header

    ######################################
    # Determine the dispersion and spatial axis
    ######################################

    # Determine dispersion axis
    disp_axis = flat_hdr.get('DISPAXIS', None)

    if disp_axis not in (1, 2):
        raise ValueError("DISPAXIS not defined or invalid in header")

    # Determine spatial axis
    spatial_axis = 0 if disp_axis == 1 else 1
    dispersion_axis = 1 if disp_axis == 1 else 0

    ######################################
    # Get the response in the dispersion-axis
    ######################################

    # Find the brightest pixs in the spatial axis
    mid_disp_pix = flat.shape[dispersion_axis] // 2
    disp_start = max(0, mid_disp_pix-5)
    disp_end   = min(flat.shape[dispersion_axis], mid_disp_pix+6)
    if dispersion_axis == 0:
        profile_region = flat[disp_start:disp_end, :]
        mid_spatial_data = np.nanmedian(profile_region, axis=dispersion_axis)
    else:
        profile_region = flat[:, disp_start:disp_end]
        mid_spatial_data = np.nanmedian(profile_region, axis=dispersion_axis)

    brightest_pix = np.nanargmax(mid_spatial_data)
    
    # Get the response of the flat_combined file
    start = max(0, brightest_pix - width//2)
    end   = min(flat.shape[spatial_axis], brightest_pix + width//2 + 1)

    if spatial_axis == 0:
        region = flat[start:end, :]
    else:
        region = flat[:, start:end]

    response = np.nanmedian(region, axis=spatial_axis)

    if plot_response:
        
        fig, ax = plt.subplots(figsize=(16, 8))
        ax.plot(response, lw = 2, color = 'blue', label = 'Response')
        ax.grid()
        ax.set_title('Response on dispersion axis')
        ax.set_xlabel('Pixels')
        ax.set_ylabel('Counts')
        ax.legend()
        plt.show()

    ######################################
    # Construct the flat_combined model image normalized
    ######################################

    if disp_axis == 2:
        norm = response[:, None]
    elif disp_axis == 1:
        norm = response[None, :]

    flat_response = flat / norm
    
    ######################################
    # Save the flat_response
    ###################################### 
    flat_response_hdr = flat_hdr.copy()

    flat_response_path = output_dir / "flat_master.fits"

    fits.PrimaryHDU(data=flat_response, header=flat_response_hdr).writeto(str(flat_response_path), overwrite=True)
    
    # Plot the statistics of flat_master.fits
    ######################################
    if view_stats:

        print("Master Flat Statistics")
        print("----------------------")
        print(f"Npix        : {flat_response.size}")
        print(f"Mean        : {np.nanmean(flat_response):.2f}")
        print(f"Median      : {np.nanmedian(flat_response):.2f}")
        print(f"Std         : {np.nanstd(flat_response):.5f}")
        print(f"Min         : {np.nanmin(flat_response):.5f}")
        print(f"Max         : {np.nanmax(flat_response):.5f}")

    ######################################
    # Correct each file using the flat_master
    ######################################
    if correct:
        print('Response correction applied to:')
    
        for f in files:
            with fits.open(f) as hdul:
                data = hdul[0].data.astype(float)
                hdr = hdul[0].header

            if data.shape != flat_response.shape:
                raise ValueError(
                    f"Image {f} has shape {data.shape}, "
                    f"but master flat has shape {flat_response.shape}.")

            data = data / flat_response

            hdr.add_history('--- Response correction ---')
            hdr.add_history('Response correction was made using')
            hdr.add_history(str(flat_response_path))

            if overwrite == True:
                out_file = f
            else:
                p = Path(f)
                out_file = output_dir / (p.stem + "_f" + p.suffix)

            fits.writeto(out_file, data, hdr, overwrite=overwrite)
            print(f"File : {out_file}")




